export type NotificationRow = {
  id: string;
  title: string;
  body: string | null;
  category: string;
  priority: "low" | "normal" | "high" | "critical";
  link: string | null;
  read_at: string | null;
  created_at: string;
};

/** Current user's notification feed (database-backed, generated by workflow triggers). */
export function useNotificationFeed(limit = 6) {
  const { user } = useAuth();
  return useQuery({
    queryKey: ["notification-feed", user?.id, limit],
    enabled: !!user,
    staleTime: 15_000,
    queryFn: async () => {
      const { data, error } = await supabase
        .from("notifications")
        .select("*")
        .is("archived_at", null)
        .order("created_at", { ascending: false })
        .limit(limit);
      if (error) throw new Error(error.message);
      return (data ?? []) as unknown as NotificationRow[];
    },
  });
}

