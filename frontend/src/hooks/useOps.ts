/** Fetch PSA master berths table with diagnostic logging and fallback. */
export function useBerths() {
  const { user, roles } = useAuth();
  return useQuery({
    queryKey: ["berths", "all"],
    staleTime: 30_000,
    queryFn: async () => {
      const { data, error } = await supabase
        .from("berths")
        .select("*")
        .order("terminal_name", { ascending: true })
        .order("code", { ascending: true });

      // Diagnostic logging (Requirement 10)
      console.log(
        `[BERTH DIAGNOSTICS]\n` +
        `authenticated user id: ${user?.id ?? "none"}\n` +
        `user role: ${roles[0] ?? "none"}\n` +
        `number of berths returned: ${data?.length ?? 0}\n` +
        `supabase error: ${error?.message ?? "none"}\n` +
        `first returned berth: ${data?.[0]?.code ?? "none"}`
      );

      if (error) {
        console.warn("Using master berth dataset fallback due to PostgREST error:", error.message);
        return MASTER_PSA_BERTHS;
      }

      const list = (data ?? []) as unknown as BerthRow[];
      return list.length > 0 ? list : MASTER_PSA_BERTHS;
    },
  });
}

